for (const locale of LOCALES) {
  const filePath = new URL(`../extension/_locales/${locale}/messages.json`, import.meta.url);
  const data = JSON.parse(readFileSync(filePath, "utf8"));

  if (data.extDescription?.message) {
    data.extDescription.message = data.extDescription.message.replace(/(?:7[57]|95)\+/g, "97+");
    if (locale === "id") {
      data.extDescription.message = data.extDescription.message.replace("melalui", "via");
    }
  }

  for (const [key, translations] of Object.entries(TRANSLATIONS)) {
    const text = translations[locale] || translations.en;
    data[key] = { message: text };
  }

  writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`Updated ${locale}: ${Object.keys(data).length} keys`);
}

